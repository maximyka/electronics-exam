# 1. Fix KaTeX strings in all question summaries
for q in data["questions"]:
    s = q["summary"]
    # Fix double backslashes before known LaTeX commands
    # e.g. \\frac -> \frac, \\varphi -> \varphi, \\cdot -> \cdot, etc.
    cmds = ["frac", "varphi", "cdot", "left", "right", "approx", "text", "Delta", "sqrt", 
            "sum", "prod", "partial", "int", "infty", "omega", "pi", "tau", "mu", "alpha", 
            "beta", "gamma", "theta", "lambda", "pm", "ge", "le", "gg", "ll", "sim", 
            "implies", "quad", "qquad", "circ", "times", "parallel", "to", "dots"]
    for c in cmds:
        # replace \\cmd with \cmd
        s = re.sub(r'\\\\' + c, r'\\' + c, s)
        # replace any remaining ^\\circ with ^{\circ}
        s = re.sub(r'\^\\*circ', r'^{\\circ}', s)
    
    # Specific fixes:
    # Q1: \left(e^{\frac{e U}{m k T}} - 1\right)
    # Ensure delimiters and brackets match
    s = s.replace(r'\right)', r'\right)')
    
    # Question 13: theta = 180^\circ -> theta = 180^{\circ}
    s = re.sub(r'(\d+)\^\\*circ', r'\1^{\\circ}', s)
    s = re.sub(r'(\d+)\^\{\\+circ\}', r'\1^{\\circ}', s)
    
    # Question 15: \varphi_\gamma -> \varphi_{\gamma}
    s = s.replace(r'\varphi_\gamma', r'\varphi_{\gamma}')
    s = s.replace(r'\varphi_K', r'\varphi_{K}')
    
    # Question 36: -60^\circ -> -60^{\circ}
    s = re.sub(r'(-?\d+)\^\\*circ', r'\1^{\\circ}', s)

    q["summary"] = s

